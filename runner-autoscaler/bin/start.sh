#!/usr/bin/env bash
# Bootstrap the runner-autoscaler stack on any host with vault access.
#
# Reads the runner-autoscaler AppRole credentials from the local-secrets
# vault file (Drive mount path is auto-detected per host), uses them to
# fetch the cloudflared connector token from vault.wopr.bot, writes a
# fresh .env, ensures the wopr-runners docker network exists, and runs
# `docker compose up -d`.
#
# Idempotent — safe to re-run; .env is overwritten each time.
#
# Usage:  bin/start.sh           # bring up the stack
#         bin/start.sh --build   # rebuild image first
#         bin/start.sh restart   # docker compose restart  (after config edit)
#         bin/start.sh down      # docker compose down

set -euo pipefail

# Locate the local-secrets directory across hosts.
# Battleaxe (WSL2):    /mnt/g/My Drive/vault/local-secrets
# macOS (Drive):       ~/Library/CloudStorage/GoogleDrive-<email>/My Drive/vault/local-secrets
VAULT_DIR=""
for candidate in \
  "/mnt/g/My Drive/vault/local-secrets" \
  "$HOME/Library/CloudStorage/GoogleDrive-evilgenius@nefariousplan.com/My Drive/vault/local-secrets"; do
  if [ -d "$candidate" ]; then
    VAULT_DIR="$candidate"
    break
  fi
done

if [ -z "$VAULT_DIR" ]; then
  echo "ERROR: vault local-secrets directory not found on this host" >&2
  echo "  expected one of:" >&2
  echo "    /mnt/g/My Drive/vault/local-secrets" >&2
  echo "    ~/Library/CloudStorage/GoogleDrive-*/My Drive/vault/local-secrets" >&2
  exit 1
fi

APPROLE_FILE="$VAULT_DIR/2026-04-09-tsavo-runner-autoscaler-approle.txt"
if [ ! -f "$APPROLE_FILE" ]; then
  echo "ERROR: AppRole credentials file missing: $APPROLE_FILE" >&2
  exit 1
fi

if ! command -v vault >/dev/null 2>&1; then
  echo "ERROR: vault CLI not in PATH (install via brew install hashicorp/tap/vault or apt install vault)" >&2
  exit 1
fi

if ! command -v docker >/dev/null 2>&1; then
  echo "ERROR: docker not in PATH" >&2
  exit 1
fi

# Parse AppRole creds out of the vault file (low-tier .txt with KEY=VALUE lines below the --- separator)
RID=$(awk -F= '/^VAULT_ROLE_ID=/{print $2}' "$APPROLE_FILE")
SID=$(awk -F= '/^VAULT_SECRET_ID=/{print $2}' "$APPROLE_FILE")
if [ -z "$RID" ] || [ -z "$SID" ]; then
  echo "ERROR: AppRole creds malformed in $APPROLE_FILE" >&2
  exit 1
fi

export VAULT_ADDR=https://vault.wopr.bot
echo "==> logging in to $VAULT_ADDR via AppRole"
VTOK=$(vault write -field=token auth/approle/login role_id="$RID" secret_id="$SID")
if [ -z "$VTOK" ]; then
  echo "ERROR: vault AppRole login failed" >&2
  exit 1
fi

echo "==> fetching CLOUDFLARED_TUNNEL_TOKEN from secret/shared/cloudflare"
CONN=$(VAULT_TOKEN="$VTOK" vault kv get -field=runner_autoscaler_tunnel_token secret/shared/cloudflare)
if [ -z "$CONN" ]; then
  echo "ERROR: tunnel token not found in vault — has the tunnel been provisioned?" >&2
  exit 1
fi

# Where do compose files live?
COMPOSE_DIR="$(cd "$(dirname "$0")/.." && pwd)"
cd "$COMPOSE_DIR"

echo "==> writing $COMPOSE_DIR/.env"
umask 077
cat > .env <<EOF
# Auto-generated by bin/start.sh — do not edit by hand.
# Values fetched from vault.wopr.bot via the runner-autoscaler AppRole.
VAULT_ADDR=https://vault.wopr.bot
VAULT_ROLE_ID=$RID
VAULT_SECRET_ID=$SID
CLOUDFLARED_TUNNEL_TOKEN=$CONN
GITHUB_ORG=wopr-network
RUNNER_NETWORK=wopr-runners
GITHUB_REPOS=TSavo/nefariousplan,TSavo/provekit
IDLE_TIMEOUT_MINUTES=30
MAX_RUNNERS=5
EOF
unset RID SID VTOK CONN

echo "==> ensuring docker network 'wopr-runners' exists"
docker network inspect wopr-runners >/dev/null 2>&1 || \
  docker network create wopr-runners --driver bridge

# Dispatch on argument
case "${1:-up}" in
  up)
    echo "==> docker compose up -d"
    docker compose up -d
    ;;
  --build)
    echo "==> docker compose up -d --build"
    docker compose up -d --build
    ;;
  restart)
    echo "==> docker compose restart"
    docker compose restart
    ;;
  down)
    echo "==> docker compose down"
    docker compose down
    ;;
  *)
    echo "==> docker compose $*"
    docker compose "$@"
    ;;
esac
